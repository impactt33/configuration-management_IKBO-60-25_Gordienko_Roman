#!/bin/bash
# Проверка параметра --script: стартовые скрипты эмулятора.
# Каждый вызов открывает окно, закройте его, чтобы перейти к следующему.

cd "$(dirname "$0")/.." || exit

echo "1. Скрипт без ошибок: выполняются все команды, комментарии не выполняются"
./run.sh --script scripts/no_errors.txt

echo "2. Скрипт с ошибкой: выполнение останавливается на неизвестной команде"
./run.sh --script scripts/with_errors.txt

echo "3. Скрипт с exit: эмулятор закрывается сам"
./run.sh --script scripts/with_exit.txt

echo "4. Несуществующий скрипт: сообщение об ошибке, эмулятор работает"
./run.sh --script scripts/missing.txt
